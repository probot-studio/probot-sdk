#!/usr/bin/env python3
"""Generate the header-check translation units (design/PORT.md section 5).

One TU per public header: `#include <Arduino.h>` (target build) followed by the header, so every
header is compiled on its own, after the Arduino macros, with the exact build flags. The list is
every public header in tools/upstream/generated.txt (src/ minus src/prosdk/impl/) plus the
hand-written headers in src/. Writes only changed files, removes stale ones and prints the TU
paths (one per line) for CMake.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GENERATED = ROOT / "tools" / "upstream" / "generated.txt"
HEADER_EXTS = {".h", ".hpp", ""}  # "" = extensionless C++ headers (util/scope)
# Not listed: src/prosdk/platform/hal/esp32/ (backend-internal headers of the archive build) and
# src/prosdk/probot/ (sketch side; needs <probot.h>, checked by the sketch compiles).
HAND_WRITTEN_GLOBS = ["src/prosdk.h", "src/prosdk/cxx/*.hpp", "src/prosdk/platform/*.hpp",
                      "src/prosdk/platform/dashboard/*.hpp", "src/prosdk/platform/hal/*.hpp",
                      "src/prosdk/drivers/**/*.hpp"]

# Headers that are not meant to be compiled on their own (path -> reason).
NOT_STANDALONE: dict[str, str] = {
    "src/prosdk.h":
        "on the robot it includes <probot.h> from the separate probot-core library, which is not "
        "on the archive include path; checked by the sketch compiles (examples/HalSmoke)",
}
# Same, by pattern (regex on the repo-relative path -> reason).
NOT_STANDALONE_PATTERNS: dict[str, str] = {
    r"^src/prosdk/thirdparty/eigen/(unsupported/)?Eigen/src/":
        "Eigen internal header (IWYU private; errors unless included through its module header)",
    r"^src/prosdk/thirdparty/gcem/gcem_incl/":
        "gcem internal header (uses GCLIM, return_t, GCEM_* that only gcem.hpp declares first)",
    r"^src/prosdk/thirdparty/apriltag/common/(doubles|floats)\.h$":
        "AprilTag C-only header (static inline functions convert void* implicitly, invalid C++); "
        "no prosdk or AprilTag source includes it",
    r"^src/prosdk/thirdparty/apriltag/common/doubles_floats_impl\.h$":
        "AprilTag C template fragment (needs TNAME etc. from doubles.h/floats.h)",
}


def public_headers() -> list[str]:
    out = set()
    for ln in GENERATED.read_text().splitlines():
        if not ln or ln.startswith("#"):
            continue
        _, path = ln.split(" ", 1)
        if (path.startswith("src/") and not path.startswith("src/prosdk/impl/")
                and Path(path).suffix in HEADER_EXTS):
            out.add(path)
    for g in HAND_WRITTEN_GLOBS:
        for p in ROOT.glob(g):
            out.add(p.relative_to(ROOT).as_posix())
    return sorted(p for p in out if p not in NOT_STANDALONE
                  and not any(re.search(rx, p) for rx in NOT_STANDALONE_PATTERNS))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--target-hw", type=int, choices=(0, 1), required=True)
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    want = {}
    for h in public_headers():
        inc = h[len("src/"):]
        name = inc.replace("/", "__").replace(".", "_") + ".cpp"
        text = "// Generated by tools/build/header_check.py; do not edit.\n"
        if a.target_hw:
            text += "#include <Arduino.h>\n"
        text += f"#include <{inc}>\n"
        want[name] = text
    for f in a.out.glob("*.cpp"):
        if f.name not in want:
            f.unlink()
    for name, text in sorted(want.items()):
        f = a.out / name
        if not f.exists() or f.read_text() != text:
            f.write_text(text)
        print(f)
    return 0


if __name__ == "__main__":
    sys.exit(main())
